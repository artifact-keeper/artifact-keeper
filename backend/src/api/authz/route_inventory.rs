//! Test support: list the routes of an assembled Axum router.
//!
//! Axum 0.7 offers no public route-listing API, so this reads the router's
//! `Debug` output. That representation is not a stable interface; the parser
//! pins to the Axum 0.7 layout and panics, rather than returning a partial
//! list, when the layout is not what it expects. Revisit on an Axum upgrade.

use std::collections::{BTreeSet, HashMap};
use std::path::PathBuf;

use axum::Router;

use super::registry::RouteKey;

const VERBS: &[&str] = &[
    "get", "head", "delete", "options", "patch", "post", "put", "trace", "connect",
];

/// All `(METHOD, path)` pairs routed by `router`, paths as registered
/// (`:param` syntax, including any `nest` prefixes).
pub(crate) fn enumerate_routes<S>(router: &Router<S>) -> BTreeSet<RouteKey> {
    let dbg = format!("{router:?}");
    // Only the primary path router; the fallback router follows it.
    let primary = &dbg[..dbg
        .find("fallback_router:")
        .expect("Axum Debug layout changed: no `fallback_router`")];
    let routes_at = primary
        .find("routes: {")
        .expect("Axum Debug layout changed: no `routes`");
    let node_at = primary
        .find("node: Node { paths: {")
        .expect("Axum Debug layout changed: no `node` paths");
    let routes = &primary[routes_at..node_at];
    let paths = &primary[node_at..];

    let mut path_by_id = HashMap::new();
    for chunk in paths.split("RouteId(").skip(1) {
        let (id, rest) = chunk
            .split_once("): \"")
            .expect("Axum Debug layout changed: route id");
        let (path, _) = rest
            .split_once('"')
            .expect("Axum Debug layout changed: route path");
        path_by_id.insert(id.to_string(), path.to_string());
    }

    let mut out = BTreeSet::new();
    for chunk in routes.split("RouteId(").skip(1) {
        let (id, rest) = chunk
            .split_once("): MethodRouter(")
            .expect("Axum Debug layout changed: a route is not a MethodRouter");
        // Stop before `fallback:` so it is not read as a verb.
        let rest = &rest[..rest
            .find("fallback:")
            .expect("Axum Debug layout changed: no method fallback")];
        let path = path_by_id
            .get(id)
            .unwrap_or_else(|| panic!("Axum Debug layout changed: no path for RouteId({id})"));
        for verb in VERBS {
            let needle = format!("{verb}: ");
            let at = rest
                .find(&needle)
                .unwrap_or_else(|| panic!("Axum Debug layout changed: no `{verb}` slot"));
            if !rest[at + needle.len()..].starts_with("None") {
                out.insert((verb.to_uppercase(), path.clone()));
            }
        }
    }
    out
}

/// Set to regenerate the baseline file instead of comparing against it:
/// `AK_UPDATE_AUTHZ_BASELINE=1 cargo nextest run -p artifact-keeper-backend --lib api_v1_declarations`
pub(crate) const BASELINE_ENV: &str = "AK_UPDATE_AUTHZ_BASELINE";

const BASELINE_HEADER: &str = "\
# Live /api/v1 operations that declare no IAM authorization yet.
# Generated by the route guard test; never edit by hand.
# Regenerate: AK_UPDATE_AUTHZ_BASELINE=1 cargo nextest run --lib api_v1_declarations
# Annotating a route removes it here; a new undeclared route fails the guard.
";

pub(crate) fn baseline_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/api/authz/uncovered_api_v1_routes.txt")
}

pub(crate) fn render_baseline(routes: &BTreeSet<RouteKey>) -> String {
    let mut out = String::from(BASELINE_HEADER);
    for (method, path) in routes {
        out.push_str(&format!("{method} {path}\n"));
    }
    out
}

pub(crate) fn parse_baseline(text: &str) -> BTreeSet<RouteKey> {
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(|l| {
            let (method, path) = l
                .split_once(' ')
                .unwrap_or_else(|| panic!("malformed baseline line: {l:?}"));
            (method.to_string(), path.to_string())
        })
        .collect()
}

/// Describe how `actual` differs from the reviewed baseline, or `None` if equal.
pub(crate) fn baseline_diff(
    baseline: &BTreeSet<RouteKey>,
    actual: &BTreeSet<RouteKey>,
) -> Option<String> {
    if baseline == actual {
        return None;
    }
    let fmt = |set: Vec<&RouteKey>| {
        set.iter()
            .map(|(m, p)| format!("  {m} {p}"))
            .collect::<Vec<_>>()
            .join("\n")
    };
    let added: Vec<_> = actual.difference(baseline).collect();
    let removed: Vec<_> = baseline.difference(actual).collect();
    let mut msg = String::new();
    if !added.is_empty() {
        msg.push_str(&format!(
            "undeclared /api/v1 operations not in the baseline (declare their authorization in the handler's #[utoipa::path]):\n{}\n",
            fmt(added)
        ));
    }
    if !removed.is_empty() {
        msg.push_str(&format!(
            "baseline entries that are now declared or no longer routed (regenerate with {BASELINE_ENV}=1 and review the diff):\n{}\n",
            fmt(removed)
        ));
    }
    Some(msg)
}

/// Require the uncovered set to equal the reviewed baseline file, or rewrite
/// the file when `AK_UPDATE_AUTHZ_BASELINE` is set.
pub(crate) fn assert_matches_baseline(actual: &BTreeSet<RouteKey>) {
    let path = baseline_path();
    if std::env::var_os(BASELINE_ENV).is_some() {
        std::fs::write(&path, render_baseline(actual)).expect("write authz baseline");
        return;
    }
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "read {}: {e}; generate it with {BASELINE_ENV}=1",
            path.display()
        )
    });
    if let Some(diff) = baseline_diff(&parse_baseline(&text), actual) {
        panic!("{diff}");
    }
}

#[cfg(ak_test_shard = "services-2")]
#[cfg(test)]
mod tests {
    use super::*;
    use axum::routing::{get, post};

    fn key(m: &str, p: &str) -> RouteKey {
        (m.to_string(), p.to_string())
    }

    #[test]
    fn lists_methods_and_nested_paths() {
        let inner: Router = Router::new()
            .route("/:key/labels", get(|| async {}).put(|| async {}))
            .route(
                "/:key/labels/:label_key",
                post(|| async {}).delete(|| async {}),
            );
        let router: Router = Router::new()
            .route("/health", get(|| async {}))
            .nest("/api/v1/repositories", inner);
        assert_eq!(
            enumerate_routes(&router),
            [
                key("GET", "/health"),
                key("GET", "/api/v1/repositories/:key/labels"),
                key("PUT", "/api/v1/repositories/:key/labels"),
                key("POST", "/api/v1/repositories/:key/labels/:label_key"),
                key("DELETE", "/api/v1/repositories/:key/labels/:label_key"),
            ]
            .into()
        );
    }

    #[test]
    fn baseline_round_trips_and_reports_both_directions() {
        let set: BTreeSet<RouteKey> =
            [key("GET", "/api/v1/a/:id"), key("POST", "/api/v1/b")].into();
        assert_eq!(parse_baseline(&render_baseline(&set)), set);
        assert_eq!(baseline_diff(&set, &set), None);

        let mut grown = set.clone();
        grown.insert(key("DELETE", "/api/v1/new"));
        let msg = baseline_diff(&set, &grown).unwrap();
        assert!(msg.contains("DELETE /api/v1/new"), "{msg}");
        assert!(msg.contains("undeclared"), "{msg}");

        let mut shrunk = set.clone();
        shrunk.remove(&key("POST", "/api/v1/b"));
        let msg = baseline_diff(&set, &shrunk).unwrap();
        assert!(msg.contains("POST /api/v1/b"), "{msg}");
        assert!(msg.contains(BASELINE_ENV), "{msg}");
    }

    #[test]
    fn an_added_route_changes_the_inventory() {
        let base: Router = Router::new().route("/a", get(|| async {}));
        let extended: Router = Router::new()
            .route("/a", get(|| async {}))
            .route("/b", get(|| async {}));
        assert_ne!(enumerate_routes(&base), enumerate_routes(&extended));
    }
}
