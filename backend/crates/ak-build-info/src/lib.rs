//! Build metadata baked in at compile time: the commit, the version and the
//! Debian `Release` `Date:` floor.
//!
//! These used to come from the backend's own `build.rs`, the build script of
//! a 1.2M-line crate that also runs the proto codegen. They live in this
//! crate so that the one script reading the build environment is a tiny one
//! with nothing else to do (#6181). The values are stable across commits in
//! a dev checkout, so a commit recompiles nothing; a build that ships sets
//! `GIT_SHA` (and may set `SOURCE_DATE_EPOCH`) explicitly.

#![forbid(unsafe_code)]

// `GIT_SHA` and `RELEASE_DATE_FLOOR_EPOCH`, generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/build_info.rs"));

/// Semantic version of the build: the workspace version, which this crate
/// shares with the backend.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// Length of the short SHA form, matching the `sha-<commit>` tag emitted by the
/// Docker Publish workflow so a log line can be matched to an exact image.
pub const SHORT_SHA_LEN: usize = 7;

/// Truncate a git SHA to its short form, leaving the `"unknown"` sentinel (and
/// any value already shorter than the short length) untouched.
pub fn shorten(sha: &str) -> &str {
    if sha == "unknown" || sha.len() < SHORT_SHA_LEN {
        sha
    } else {
        &sha[..SHORT_SHA_LEN]
    }
}

/// Short (7-char) git SHA of the build, or `"unknown"` when unavailable.
pub fn short_sha() -> &'static str {
    shorten(GIT_SHA)
}
